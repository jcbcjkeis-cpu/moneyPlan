const squashName = (s) => String(s ?? '').toLowerCase().replace(/[\s/·.\-_()'"]/g, '');
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function build(dict) {
  const list = [];
  Object.entries(dict).forEach(([category, words]) => {
    new Set(words).forEach((w) => {
      const kw = squashName(w);
      if (!kw) return;
      // 짧은 영문 약어는 앞뒤가 영문/숫자가 아닐 때만 (CU ≠ CUBE, KT ≠ KTX)
      const isShortLatin = /^[a-z0-9&+]+$/.test(kw) && kw.length <= 3;
      list.push({
        kw,
        category,
        re: isShortLatin ? new RegExp(`(^|[^a-z0-9])${escapeRe(kw)}(?![a-z0-9])`) : null,
      });
    });
  });
  // 긴 단어부터 → 가장 구체적인 단어가 이김
  return list.sort((a, b) => b.kw.length - a.kw.length);
}

const EXPENSE_LIST = build(EXPENSE);
const INCOME_LIST = build(INCOME);

/** 이름으로 카테고리 추측. 못 찾으면 null */
export function guessCategory(name, { income = false } = {}) {
  const raw = String(name ?? '').toLowerCase().trim();
  if (!raw) return null;
  const sq = squashName(raw);
  const list = income ? INCOME_LIST : EXPENSE_LIST;
  for (const e of list) {
    if (e.re ? e.re.test(raw) : sq.includes(e.kw)) return e.category;
  }
  return null;
}

export const CATEGORY_KEYWORD_COUNT = EXPENSE_LIST.length + INCOME_LIST.length;
